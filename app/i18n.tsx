function interpolate(message: string, values?: MessageValues) {
  if (!values) return message;
  return message.replace(/\{([A-Za-z0-9_]+)\}/g, (match, key: string) => (
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match
  ));
}

function isLocale(value: string | null): value is Locale {
  return Boolean(value && SUPPORTED_LOCALES.includes(value as Locale));
}

function localeFromLanguage(language: string): Locale | null {
  const normalized = language.toLowerCase();
  if (normalized === "ko" || normalized.startsWith("ko-")) return "ko";
  if (normalized === "ja" || normalized.startsWith("ja-")) return "ja";
  if (normalized === "zh" || normalized.startsWith("zh-")) return "zh-Hant";
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  return null;
}

function detectBrowserLocale(): Locale {
  if (typeof navigator === "undefined") return "ko";
  for (const language of navigator.languages ?? [navigator.language]) {
    const matched = localeFromLanguage(language);
    if (matched) return matched;
  }
  return "en";
}

type I18nContextValue = {
  locale: Locale;
  localeReady: boolean;
  brandName: string;
  setLocale: (locale: Locale) => void;
  t: (key: string, values?: MessageValues) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("ko");
  const [localeReady, setLocaleReady] = useState(false);

  useEffect(() => {
    const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    setLocaleState(isLocale(stored) ? stored : detectBrowserLocale());
    setLocaleReady(true);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale === "zh-Hant" ? "zh-Hant" : locale;
    document.documentElement.dataset.locale = locale;
  }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    window.localStorage.setItem(LOCALE_STORAGE_KEY, next);
  }, []);

  const t = useCallback((key: string, values?: MessageValues) => {
    const translated = dictionaries[locale][key] ?? key;
    return interpolate(translated, values);
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    localeReady,
    brandName: BRAND_NAMES[locale],
    setLocale,
    t,
  }), [locale, localeReady, setLocale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside LocaleProvider");
  return value;
}

export function Translated({ children }: { children: ReactNode }) {
  const { t } = useI18n();

  const translateNode = (node: ReactNode): ReactNode => {
    if (typeof node === "string" && /[가-힣]/.test(node)) {
      const trimmed = node.trim();
      return `${node.slice(0, node.indexOf(trimmed))}${t(trimmed)}${node.slice(node.indexOf(trimmed) + trimmed.length)}`;
    }
    if (typeof node === "string") return node;
    if (!isValidElement(node)) return node;
    const element = node as ReactElement<{ children?: ReactNode }>;
    if (element.props.children === undefined) return element;
    return cloneElement(element, undefined, Children.map(element.props.children, translateNode));
  };

  return <>{Children.map(children, translateNode)}</>;
}
